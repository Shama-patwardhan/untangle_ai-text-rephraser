"""Analysis orchestration service coordinating statistics and pattern detectors."""

import uuid
from typing import Final

from app.config import Settings
from app.core.exceptions import AppValidationError
from app.schemas.analysis import AnalyzeResponse, Finding, TextStatistics
from app.services.detectors import run_all_detectors
from app.services.statistics import compute_text_statistics, split_sentences

STANDARD_DISCLAIMER: Final[str] = (
    "Observable writing patterns and stylistic metrics measured by Untangle "
    "describe textual characteristics only. They do not constitute proof "
    "of authorship, and cannot determine whether a text was authored by "
    "a human or generated by an artificial intelligence."
)


def generate_summary(
    statistics: TextStatistics,
    findings: list[Finding],
) -> str:
    """Generate a neutral, factual summary of the analysis results.

    Args:
        statistics: Computed text statistics.
        findings: List of pattern detector findings.

    Returns:
        Short descriptive summary string.
    """
    base_summary: str
    if not findings:
        base_summary = (
            f"Analysis of {statistics.word_count} words across "
            f"{statistics.sentence_count} sentence(s) completed. No notable "
            "repetitive phrasing, sentence uniformity, or elevated punctuation "
            "patterns met the configured detection thresholds."
        )
    else:
        # Unique rule titles preserving order
        unique_titles = list(dict.fromkeys(f.title for f in findings))
        titles_str = ", ".join(unique_titles)

        base_summary = (
            f"Analysis of {statistics.word_count} words across "
            f"{statistics.sentence_count} sentence(s) identified {len(findings)} "
            f"observable pattern(s): {titles_str}. Stylistic metrics indicate an "
            f"average sentence length of {statistics.avg_sentence_length:.1f} words "
            f"(sample standard deviation: {statistics.sentence_length_std_dev:.2f})."
        )

    # Contextual note for short texts
    if statistics.word_count < 35 or statistics.sentence_count < 3:
        short_text_note = (
            " Note: The analyzed text is very brief; statistical metrics and "
            "stylistic patterns on short samples have high variance and limited "
            "diagnostic reliability."
        )
        return f"{base_summary}{short_text_note}"

    return base_summary


def analyze_text(
    text: str,
    settings: Settings,
) -> AnalyzeResponse:
    """Coordinate end-to-end writing analysis on input text.

    Args:
        text: Input text string to analyze.
        settings: Application settings containing thresholds and max length.

    Returns:
        Complete AnalyzeResponse containing statistics, findings, and disclaimer.

    Raises:
        AppValidationError: If text exceeds configured maximum allowed length.
    """
    # Defensive length enforcement
    if len(text) > settings.max_text_length:
        raise AppValidationError(
            f"Input text length ({len(text):,} characters) exceeds maximum "
            f"allowed limit of {settings.max_text_length:,} characters."
        )

    # Deterministic statistics & segmentation
    sentences = split_sentences(text)
    statistics = compute_text_statistics(
        text=text,
        min_repeated_phrase_words=settings.min_repeated_phrase_words,
        min_phrase_repetitions=settings.min_phrase_repetitions,
    )

    # Explainable detectors
    findings = run_all_detectors(
        sentences=sentences,
        statistics=statistics,
        settings=settings,
    )

    # Synthesis
    summary = generate_summary(statistics, findings)
    analysis_id = f"ana_{uuid.uuid4().hex[:12]}"

    return AnalyzeResponse(
        analysis_id=analysis_id,
        statistics=statistics,
        findings=findings,
        summary=summary,
        disclaimer=STANDARD_DISCLAIMER,
    )
